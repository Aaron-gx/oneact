export const ICON_NAMES = Object.keys(IconSet);

/** 渲染单个图标 SVG 字符串（供复合组件内联复用；name 未知回退 circle）。 */
export function iconSvg(name: string, size = 24, color = "var(--oa-color-primary)", sw = 2): string {
  const path = IconSet[name] ?? IconSet.circle;
  return `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="${sw}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" style="flex:none">${path}</svg>`;
}

/** 取图标路径（未知回退 circle）。 */
export function iconPath(name: string): string {
  return IconSet[name] ?? IconSet.circle;
}

export function icon(el: AnyElement): string {
  if (el.type !== "icon") return "";
  const p = el.props;
  const size = p.size ?? 48;
  const sw = p.strokeWidth ?? 2;
  const color = p.color ?? "var(--oa-color-primary)";
  return `<div style="width:100%;height:100%;display:flex;align-items:center;justify-content:center;">${iconSvg(p.name, size, color, sw)}</div>`;
}
